void levelInit(void) { activeStage = 0; }

void levelSetStage(int stage)
{
    activeStage = (stage >= 0 && stage <= 2) ? stage : 0;
}

int levelIsSolid(int col, int row)
{
    if (col < 0 || col >= levelGetCols() ||
        row < 0 || row >= LEVEL_ROWS)
        return 0;

    if (activeStage == 2) {
        float x = col * TILE_SIZE, y = row * TILE_SIZE;
        for (unsigned i = 0; i < sizeof(gauntletFixed)/sizeof(gauntletFixed[0]); i++) {
            const LevelRect* r = &gauntletFixed[i];
            if (x < r->x + r->w && x + TILE_SIZE > r->x &&
                y < r->y + r->h && y + TILE_SIZE > r->y) return 1;
        }
        return 0;
    }
    const char* const* ground =
        activeStage == 1 ? groundParkour : groundZigzagging;
    return ground[row][col] == '1';
}

int levelCollides(float x, float y, float w, float h)
{
    const float epsilon = 0.001f;
    int left = (int)(x / TILE_SIZE);
    int right = (int)((x + w - epsilon) / TILE_SIZE);
    int top = (int)(y / TILE_SIZE);
    int bottom = (int)((y + h - epsilon) / TILE_SIZE);

    for (int row = top; row <= bottom; row++)
        for (int col = left; col <= right; col++)
            if (levelIsSolid(col, row))
                return 1;
    return 0;
}
